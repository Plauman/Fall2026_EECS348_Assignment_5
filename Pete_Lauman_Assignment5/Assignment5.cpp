    std::ofstream outFile;

    // Check if placing character 'c' at board[row][col] is valid
    bool isValid(int row, int col, char c) const {//Function to see if it is possible to place a value at a particular coordinate
        for (int i = 0; i < 9; ++i) {//Since both the row and collum are the same size and both need to be checked, can use one loop for both
            // Check row and column
            if (board[row][i] == c) return false;//If the row already contains the value, it cant be placed there and further execution is not needed.
            if (board[i][col] == c) return false;//If the collum alrady contains the value, it can't be placed there and the function can stop.
        }

        // Check 3x3 subgrid
        int startRow = row - row % 3;//Since the squares are 3x3, this line will return the row corresonding to the top of the square.
        int startCol = col - col % 3;//Since the squares are 3x3, this line will return the collum corresponding to the left of the square.
        for (int i = 0; i < 3; ++i) {//Iterate through the rows in the square
            for (int j = 0; j < 3; ++j) {//Iterate through the collums in the square
                if (board[startRow + i][startCol + j] == c) return false;//If the value is in the square, it can't be placed there and execution stops.
            }
        }
        return true;//If it passes all previous checks, then the value is valid and can be placed there.
    }

    // [A5 AI-ADDED] Checks that the clues supplied in the puzzle do not already contradict each other
